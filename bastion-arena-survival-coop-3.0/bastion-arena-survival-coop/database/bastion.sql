CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(24) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login_at TIMESTAMPTZ NULL
);

-- Enforce case-insensitive usernames (Kurt and kurt count as the same name).
CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_unique
  ON public.users (lower(username));

CREATE TABLE IF NOT EXISTS public.player_saves (
  user_id BIGINT PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
  profile_json JSONB NOT NULL DEFAULT '{"runs":0,"kills":0,"highestLevel":1}'::jsonb,
  best_json JSONB NOT NULL DEFAULT '{"wave":0,"score":0}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS player_saves_updated_at_idx
  ON public.player_saves (updated_at DESC);

-- Classement (v3.0). Idempotent : peut être exécuté sur une base existante sans toucher aux comptes.
CREATE TABLE IF NOT EXISTS public.leaderboard_scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  username VARCHAR(24) NOT NULL,
  mode VARCHAR(30) NOT NULL,
  score INTEGER NOT NULL CHECK (score >= 0),
  wave INTEGER NOT NULL DEFAULT 0,
  squad VARCHAR(200) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS leaderboard_scores_mode_idx ON public.leaderboard_scores (mode, score DESC);
